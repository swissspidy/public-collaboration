/**
 * Registers the collaboration request post type.
 *
 * The post type is not public and has no admin UI. It exists only so that each
 * collaboration request gets a URL, a slug to act as the token, an author, and
 * a parent — the post being collaborated on.
 *
 * @return void
 */
function register_post_type(): void {
	\register_post_type(
		Collaboration_Request::POST_TYPE,
		[
			'labels'              => [
				'name'          => _x( 'Collaboration Requests', 'post type general name', 'public-collaboration' ),
				'singular_name' => _x( 'Collaboration Request', 'post type singular name', 'public-collaboration' ),
			],
			'supports'            => [ 'author' ],
			'rewrite'             => [
				/**
				 * Filters the URL prefix of the collaboration link.
				 *
				 * @param string $slug URL prefix. Default 'collaborate'.
				 */
				'slug'       => apply_filters( 'public_collaboration_rewrite_slug', 'collaborate' ),
				'with_front' => false,
				'feeds'      => false,
				'pages'      => false,
			],
			'public'              => false,
			'publicly_queryable'  => true,
			'show_ui'             => false,
			'show_in_menu'        => false,
			'show_in_rest'        => false,
			'has_archive'         => false,
			'can_export'          => false,
			'exclude_from_search' => true,
			'delete_with_user'    => true,

			/*
			 * Without this, a site on plain permalinks would address the
			 * collaboration page as `?post_type=…&p=123` — a guessable post ID
			 * standing in for an unguessable token. With it, the token is in the
			 * URL either way.
			 */
			'query_var'           => Collaboration_Request::POST_TYPE,
		]
	);
}

/**
 * Registers the REST API routes.
